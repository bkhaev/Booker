<?php

// Скрипт обновляет данные в базе: книги, авторов, жанров.

// Подключается скрипт, отвечающий за подключение к БД и скрипт с вспомогательными функциями.
require_once '../service/config.php';
require_once '../service/bookerlib.php';






////////////////////////
// Настройка парсинга //
////////////////////////


// В качестве парсинга берётся сайт book24.ru, а именно 2 страница новинок. Инициализируется curl.
// На сайте книга имеет только 1 жанр, на странице нет описания. Автор может отсутствовать.
$url = 'https://book24.ru/catalog/page-2/';

try
{
    $curl = curl_init($url);

    curl_setopt($curl, CURLOPT_RETURNTRANSFER, 1);
    $page = curl_exec($curl);
    
    $page = mb_convert_encoding($page, 'HTML-ENTITIES', "UTF-8");
    $dom = new DomDocument();
    @ $dom->loadHTML($page);
    
    $xpath = new DOMXpath($dom);
    $booksView = $xpath->query("//article[@class='product-card']");
}
catch (Exception $e)
{
    echo 'Ошибка при настройке парсинга';
    return;
}


////////////////////////
// Настройка парсинга //
////////////////////////






/////////////////////
// Обработка сайта //
/////////////////////


// Сбор: книг, жанров, авторов, связанных id книг и жанров, связанных id книг и авторов соответственно.
$dataBooks = $dataGenres = $dataAuthors = $dataBooksGenres = $dataBooksAuthors = [];

// Перебор страницы: поиск книг
foreach ($booksView as $book) {
    $name = $book->getAttribute('data-b24-name');
    $genre = $book->getAttribute('data-b24-category');
    $authors = $xpath->query("./div[@class='product-card__content']/div[@class='author-list product-card__authors-holder']/*[@class='author-list__item' or @class='author-list__item smartLink']", $book);
    $image = $xpath->query("./div[@class='product-card__image-holder']//img", $book)[0];
    $description = rand(0, 3) ? getRandomDescription() : '';

    $dataBooks[] = [$name, $description, $image->getAttribute('data-src')];


    // Обработка жанра
    // Если жанр встречается впервые, он заносится в массив
    // Если уже был, берётся его id для связки
    if ($genre)
    {
        $genreid = array_search($genre, $dataGenres);
        if ($genreid === false)
        {
            $dataGenres[] = $genre;
            $genreid = count($dataGenres) - 1;
        }
        $dataBooksGenres[] = [count($dataBooks), $genreid + 1];
    }


    // Обработка авторов
    // Если автор встречается впервые, он заносится в массив
    // Если уже был, берётся его id для связки
    foreach ($authors as $author)
    {
        $author = $author->textContent;
        $authorParts = explode(' ', $author);

        if (count($authorParts) === 2)
            $authorid = array_search($author, array_map(fn($a) => trim("{$a[1]} {$a[0]}"), $dataAuthors));
        else
            $authorid = array_search($author, array_map(fn($a) => trim("{$a[0]} {$a[1]} {$a[2]}"), $dataAuthors));

        if ($authorid === false)
        {
            if (count($authorParts) === 2)
                $dataAuthors[] = [$authorParts[1], $authorParts[0], ''];
            else if (count($authorParts) === 3)
                $dataAuthors[] = [$authorParts[0], $authorParts[1], $authorParts[2]];
            else
                $dataAuthors[] = ['', $author, ''];
            $authorid = count($dataAuthors) - 1;
        }
        $dataBooksAuthors[] = [count($dataBooks), $authorid + 1];
    }
}


/////////////////////
// Обработка сайта //
/////////////////////






////////////////////////////
// Обновление базы данных //
////////////////////////////


// Происходит подключение к БД.
// Запускается транзакция: если произойдёт ошибка во время удаления данных или после удаления, изменений в БД не будет, все старые данные сохранятся.

$link = mysqli_connect($host, $user, $password, $database) or die('Ошибка подключения к БД.');

mysqli_report(MYSQLI_REPORT_ERROR | MYSQLI_REPORT_STRICT);
mysqli_begin_transaction($link);

try
{
    // Одним запросом очищаем БД

    mysqli_multi_query($link, 'DELETE FROM `genres`;DELETE FROM `authors`;DELETE FROM `books`;');

    $cleanGenresResult = mysqli_store_result($link);
    mysqli_next_result($link);
    $cleanAuthorsResult = mysqli_store_result($link);
    mysqli_next_result($link);
    $cleanBooksResult = mysqli_store_result($link);
    mysqli_next_result($link);

    if (mysqli_error($link))
    {
        echo 'Ошибка очистки БД';
        return;
    }




    // Постепенно добавляем новые данные в БД

    $qGenresParameters = $qAuthorsParameters = $qBooksParameters = $qBooksGenresParameters = $qBooksAuthorsParameters = [];


    // Добавление всех жанров
    foreach ($dataGenres as $key => &$genre)
        $qGenresParameters[] = [$key + 1, &$genre];

    $result = libSqlInsert($link, 'INSERT INTO `genres`(`id`,`name`) VALUES (?,?);', $qGenresParameters);

    if (mysqli_error($link))
    {
        echo 'Ошибка вставки жанров в БД';
        return;
    }


    // Добавление всех авторов
    foreach ($dataAuthors as $key => &$author)
        $qAuthorsParameters[] = [$key + 1, &$author[0], &$author[1], &$author[2]];

    $result = libSqlInsert($link, 'INSERT INTO `authors`(`id`,`surname`,`name`,`patronymic`) VALUES (?,?,?,?);', $qAuthorsParameters);

    if (mysqli_error($link))
    {
        echo 'Ошибка вставки авторов в БД';
        return;
    }


    // Добавление всех книг
    foreach ($dataBooks as $key => &$book)
        $qBooksParameters[] = [$key + 1, &$book[0], &$book[1], &$book[2]];

    $result = libSqlInsert($link, 'INSERT INTO `books`(`id`,`name`,`description`,`picture_name`) VALUES (?,?,?,?);', $qBooksParameters);

    if (mysqli_error($link))
    {
        echo 'Ошибка вставки книг в БД';
        return;
    }


    // Связка книг с жанрами
    foreach ($dataBooksGenres as &$genre)
        $qBooksGenresParameters[] = [&$genre[0], &$genre[1]];

    $result = libSqlInsert($link, 'INSERT INTO `genres_of_books`(`book_id`,`genre_id`) VALUES (?,?);', $qBooksGenresParameters);

    if (mysqli_error($link))
    {
        echo 'Ошибка связывания жанров с книгами';
        return;
    }


    // Связка книг с авторами
    foreach ($dataBooksAuthors as &$author)
        $qBooksAuthorsParameters[] = [&$author[0], &$author[1]];

    $result = libSqlInsert($link, 'INSERT INTO `authors_of_books`(`book_id`,`author_id`) VALUES (?,?);', $qBooksAuthorsParameters);

    if (mysqli_error($link))
    {
        echo 'Ошибка связывания авторов с книгами';
        return;
    }



    // Если дошло до этого момента, значит всё выполнилось корректно: можно сохранять изменения.
    mysqli_commit($link);

    echo 'Все данные в БД были обновлены! Источник: https://book24.ru/catalog/page-2/';
}
catch (mysqli_sql_exception $exception)
{
    echo "Ошибка mysql:\n<br>";
    echo (string)$exception;
}


mysqli_close($link);


